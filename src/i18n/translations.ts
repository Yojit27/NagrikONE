/**
 * Robust translation resolver with graceful fallback
 */
export function getTranslation(lang: SupportedLanguage, key: string, fallback?: string): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en || TRANSLATIONS.hi;
  if (dict && dict[key]) {
    return dict[key];
  }
  // Try English fallback if available
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key];
  }
  // Try Hindi fallback if available
  if (TRANSLATIONS.hi && TRANSLATIONS.hi[key]) {
    return TRANSLATIONS.hi[key];
  }
  return fallback || key;
}
